import 'dart:convert';
import 'dart:io';
import 'package:flutter_test/flutter_test.dart';
import 'package:trainlog/model.dart';
import 'package:trainlog/store.dart';

void main() {
  final path = Platform.environment['CROSS_NATIVE_FIXTURE'];
  test('native Swift backup imports and re-exports without changing fields', () async {
    final text = await File(path!).readAsString();
    final native = decodeBackup(text);
    final dir = await Directory.systemTemp.createTemp('trainlog-interop-');
    final store = await TrainingStore.open('${dir.path}/record.db', objects(native['exercises']));
    try {
      expect(await store.importBackup(native), isTrue);
      final exported = store.exportBackup();
      for (final key in ['sessions', 'exercises', 'templates', 'bodyWeights', 'plans', 'settings']) { expect(exported[key], native[key], reason: key); }
      await File('../artifacts/native-roundtrip.json').writeAsString(jsonEncode(exported));
    } finally { await store.close(); await dir.delete(recursive: true); }
  }, skip: path == null ? 'Native fixture is generated by the macOS interoperability job' : false);
}
